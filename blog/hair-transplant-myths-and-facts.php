<h2>How a Hair Transplant Works</h2>
<p>In pattern baldness, follicles on the top and front of the scalp are sensitive to the hormone DHT and gradually shrink. Follicles at the back and sides are usually much less sensitive. A transplant takes follicles from this "donor" area and places them in thinning areas, where they generally continue to behave like donor hair. The main techniques are:</p>
<ul>
<li><strong>FUT (strip method):</strong> a thin strip of scalp is removed from the back, divided into follicular units under magnification, and implanted. It leaves a fine linear scar.</li>
<li><strong>FUE (follicular unit extraction):</strong> individual follicular units are extracted one by one with a small punch, leaving tiny dot-like scars.</li>
<li><strong>DHI:</strong> a variation of FUE in which grafts are implanted with a pen-like device rather than into pre-made slits.</li>
</ul>
<p>Which technique suits you depends on your donor hair, the area to be covered, your hairstyle and the surgeon's assessment.</p>

<h2>Myth 1: The results are instant</h2>
<p><strong>Fact:</strong> The transplanted hairs usually fall out within two to six weeks. This is expected ("shock loss") and does not mean the grafts have failed; the follicles stay in place and enter a resting phase. New hair typically begins to appear after three to four months, and most people see the final result at around 9 to 12 months, sometimes longer for the crown.</p>

