<ul class="mb-0">
<li>A hair transplant moves your own follicles from the back and sides of the scalp to thinning areas. It does not create new hair.</li>
<li>Transplanted hair usually sheds within a few weeks; new growth starts after about three to four months, and the final result takes around a year.</li>
<li>Not everyone is a suitable candidate. The cause of hair loss must be confirmed first.</li>
