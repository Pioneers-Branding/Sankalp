<h2>Myth 2: Transplanted hair will fall out again</h2>
<p><strong>Fact:</strong> Because donor follicles are relatively resistant to DHT, transplanted hair usually continues to grow long term. What can change is the hair <em>around</em> the transplant. Your original hair may keep thinning over the years, which can leave the transplanted area looking isolated if this is not planned for.</p>

<h2>Myth 3: A transplant stops further hair loss</h2>
<p><strong>Fact:</strong> A transplant redistributes hair; it does not treat the process causing pattern baldness. Many doctors recommend continuing medical treatment, such as topical minoxidil or, for some men, finasteride, to protect the remaining native hair. These medicines are prescribed after assessment because they have side effects and are not suitable for everyone.</p>

<h2>Myth 4: Anyone who is going bald can have a transplant</h2>
<p><strong>Fact:</strong> A good candidate usually has:</p>
<ul>
<li>A confirmed diagnosis of pattern hair loss, or another suitable cause such as a stable scar</li>
<li>Enough healthy donor hair to cover the area realistically</li>
<li>Hair loss that has reasonably stabilised; very young men whose loss is still progressing are often advised to wait</li>
<li>Good general health, with conditions such as diabetes or high blood pressure under control</li>
<li>Realistic expectations about density</li>
</ul>
<p>A transplant is generally not the answer for hair loss from thyroid disease, iron deficiency, recent illness (telogen effluvium), active patchy hair loss (alopecia areata) or some scarring scalp conditions. These need diagnosis and treatment of their own; see <a href="/blog/hair-fall-myths-and-facts">hair fall myths and facts</a> for common medical causes.</p>

<h2>Myth 5: It is extremely painful</h2>
<p><strong>Fact:</strong> The procedure is done under local anaesthesia. The anaesthetic injections sting at first, and the session itself can be long and tiring, but most people describe it as uncomfortable rather than very painful. Some soreness, tightness and swelling for a few days afterwards is common and is usually managed with prescribed pain relief.</p>

<h2>Myth 6: FUE leaves no scars</h2>
<p><strong>Fact:</strong> FUE leaves many tiny round scars across the donor area; FUT leaves a single fine line. In both cases, the scars are usually hidden by surrounding hair, but they may be visible with a very short buzz cut. People who form thick or raised scars (keloids) should discuss this with the surgeon in advance.</p>

<h2>Myth 7: Hair transplants are only for men</h2>
<p><strong>Fact:</strong> Women can be suitable candidates in some situations, for example a stable, well-defined area of thinning, hair loss from long-term tight hairstyles (traction alopecia), or scars. Because hair loss in women often has hormonal, thyroid or nutritional causes, a full medical assessment is especially important before surgery is considered.</p>

<h2>Myth 8: It is a simple cosmetic job, so any clinic will do</h2>
<p><strong>Fact:</strong> A hair transplant is surgery. It involves local anaesthetic, incisions and wound care, and carries risks such as bleeding, infection, poor graft survival and an unnatural hairline. It should be performed by a qualified, registered doctor, usually a dermatologist or plastic surgeon trained in hair restoration, with a trained team in a properly equipped facility. Be cautious of offers that guarantee a fixed graft count or "100% density" before anyone has examined your scalp, or of prices that seem far below the norm.</p>

<h2>Questions to Ask Before Surgery</h2>
<ol>
<li>What is causing my hair loss, and has it been confirmed?</li>
<li>Who will perform the procedure, and what are their qualifications and registration?</li>
<li>Which parts will the doctor do personally, and which will technicians do?</li>
<li>How many grafts do I need, and does my donor area support that safely?</li>
<li>Which technique do you recommend for me, and why?</li>
<li>What will my hairline look like, now and as I get older?</li>
<li>What medicines should I continue or stop beforehand? (Do not stop blood thinners or other prescribed medicines without your doctor's advice.)</li>
<li>What does the estimate include, and is it given in writing?</li>
</ol>
