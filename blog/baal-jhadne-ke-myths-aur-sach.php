<h2>मिथक 1: रोज़ सिर धोने से बाल ज़्यादा झड़ते हैं</h2>
<p><strong>सच्चाई:</strong> नहाते समय जो बाल निकलते हैं, वे पहले ही जड़ से अलग हो चुके होते हैं; शैम्पू उन्हें सिर्फ़ धोकर बाहर निकालता है। अगर आप कई दिन बाद सिर धोते हैं, तो एक साथ ज़्यादा बाल दिखते हैं और लगता है कि धोने से बाल झड़ रहे हैं। बाल धोने की संख्या से जड़ों (Follicles) पर कोई असर नहीं पड़ता।</p>
<p>हाँ, बहुत गर्म पानी, गीले बालों को तौलिये से ज़ोर से रगड़ना या गीले बालों में ज़ोर से कंघी करना बालों को तोड़ सकता है। गुनगुना पानी, हल्का शैम्पू और हल्के हाथ से पोंछना बेहतर है।</p>

<h2>मिथक 2: तेल लगाने से नए बाल उगते हैं, और जितना ज़्यादा तेल उतना अच्छा</h2>
<p><strong>सच्चाई:</strong> तेल लगाना हमारी परंपरा का हिस्सा है और इसके फ़ायदे भी हैं — तेल बालों को मुलायम बनाता है, रूखापन और टूटना कम करता है, और नारियल तेल बालों के प्रोटीन को कुछ हद तक सुरक्षित रख सकता है। लेकिन बाल त्वचा के नीचे की जड़ से उगते हैं, और इस बात का कोई ठोस प्रमाण नहीं है कि तेल लगाने से बंद जड़ें दोबारा सक्रिय हो जाती हैं या गंजापन ठीक होता है।</p>
<p>ज़्यादा तेल भी ठीक नहीं। जिन लोगों को रूसी (Dandruff) की समस्या है, उनमें रात भर भारी तेल लगाए रखने से खुजली और पपड़ी बढ़ सकती है।</p>

<h2>मिथक 3: मुंडन कराने या बाल कटवाने से बाल घने आते हैं</h2>
<p><strong>सच्चाई:</strong> बाल कटवाने से दोमुंहे सिरे (Split Ends) हट जाते हैं, इसलिए बाल अच्छे दिखते हैं, लेकिन जड़ों की संख्या या बढ़ने की रफ़्तार नहीं बदलती। बच्चों के मुंडन के बाद नए बाल शुरुआत में थोड़े मोटे या गहरे लग सकते हैं, क्योंकि कटे हुए बालों का सिरा कुंद होता है। पर असल में घनापन वही रहता है। मुंडन एक पारिवारिक या धार्मिक परंपरा के रूप में ठीक है, बस इसे घने बालों का उपाय न समझें।</p>

<h2>मिथक 4: गंजापन सिर्फ़ माँ या नाना की तरफ़ से आता है</h2>
<p><strong>सच्चाई:</strong> पैटर्न गंजापन (Androgenetic Alopecia) कई जीन से तय होता है, जो <em>माता और पिता दोनों</em> से मिलते हैं। इससे जुड़ा एक जीन X क्रोमोसोम पर होता है, जो पुरुषों को माँ से मिलता है; इसी वजह से यह मिथक बना। लेकिन पिता के परिवार में गंजापन हो, तो भी संभावना बढ़ती है। पारिवारिक इतिहास से जोखिम का अंदाज़ा मिलता है, पर यह तय नहीं होता कि बाल कब और कितने झड़ेंगे।</p>

<h2>मिथक 5: एक सफ़ेद बाल तोड़ने से और सफ़ेद बाल उग आते हैं</h2>
<p><strong>सच्चाई:</strong> हर बाल की जड़ अलग होती है। एक सफ़ेद बाल तोड़ने से आस-पास के बाल सफ़ेद नहीं होते। लेकिन बार-बार बाल उखाड़ने से उस जड़ को नुकसान पहुँच सकता है, और कुछ समय बाद वहाँ बाल उगना बंद भी हो सकता है। इसलिए सफ़ेद बाल उखाड़ने के बजाय काटना बेहतर है। कम उम्र में बहुत ज़्यादा सफ़ेद बाल हों, तो विटामिन B12 की कमी या थायरॉयड की जांच कराना ठीक रहता है।</p>

<h2>मिथक 6: प्याज़ का रस या घरेलू नुस्खे गंजापन ठीक कर देते हैं</h2>
<p><strong>सच्चाई:</strong> प्याज़ के रस पर एक छोटे अध्ययन में गोल चकत्तों वाले बाल झड़ने (Alopecia Areata) में कुछ फ़ायदा दिखा था, लेकिन पैटर्न गंजेपन को ठीक करने का कोई ठोस प्रमाण नहीं है। प्याज़, नींबू या लहसुन जैसी चीज़ें संवेदनशील त्वचा पर जलन और चकत्ते भी पैदा कर सकती हैं। कोई भी नुस्खा आज़माएँ तो पहले छोटी जगह पर लगाकर देखें, और घरेलू नुस्खों के चक्कर में अचानक या चकत्तों में झड़ते बालों की जांच टालें नहीं।</p>

<h2>मिथक 7: टोपी या हेलमेट पहनने से गंजापन होता है</h2>
<p><strong>सच्चाई:</strong> टोपी या हेलमेट से बालों की जड़ों तक खून पहुँचना बंद नहीं होता और इससे पैटर्न गंजापन नहीं होता। दोपहिया चलाते समय हेलमेट ज़रूर पहनें; बस उसे साफ़ और सूखा रखें।</p>
<p>असल नुकसान लगातार खिंचाव से होता है। बहुत कसी हुई चोटी, जूड़ा या पोनीटेल, या लंबे समय तक हेयर एक्सटेंशन पहनने से माथे और कनपटी के पास बाल झड़ने लगते हैं। इसे <strong>ट्रैक्शन एलोपेसिया</strong> कहते हैं। समय रहते खिंचाव बंद करने पर बाल अक्सर वापस आ जाते हैं।</p>

<h2>मिथक 8: हेयर ट्रांसप्लांट के बाल नकली दिखते हैं और कुछ समय बाद झड़ जाते हैं</h2>
<p><strong>सच्चाई:</strong> हेयर ट्रांसप्लांट में आपके अपने बाल सिर के पीछे और किनारों से लेकर पतले हिस्से में लगाए जाते हैं। ये जड़ें गंजापन पैदा करने वाले हार्मोन (DHT) से कम प्रभावित होती हैं, इसलिए सामान्यतः लंबे समय तक बढ़ती रहती हैं। सही योजना और अनुभवी डॉक्टर के हाथों में परिणाम प्राकृतिक दिख सकते हैं।</p>
