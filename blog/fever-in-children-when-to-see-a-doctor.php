<p class="lead">Fever is the single most common reason children are brought to a clinic, and the single most common reason parents lie awake. It is worth saying clearly at the start: fever itself is not the illness. It is the body's normal response to infection, it helps fight that infection, and the height of the temperature is a poor guide to how serious the underlying cause is. A child with 39&deg;C who is drinking and playing between spikes is usually far less concerning than a child with 38&deg;C who is limp and refusing fluids. This guide explains what to watch, what to do, and exactly when <strong>fever in children</strong> needs a doctor.</p>

<h2>Measuring Temperature Properly</h2>
<p>Fever is a temperature of 38&deg;C (100.4&deg;F) or above. How you measure it matters.</p>

