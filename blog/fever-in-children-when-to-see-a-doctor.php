<blockquote>"Treat the child, not the thermometer. How they are drinking, how alert they are and how they are breathing tells you far more than the number."</blockquote>

<h2>What to Do at Home</h2>
<ul>
  <li><strong>Fluids first.</strong> This is the most important thing. Offer small amounts frequently — breast milk, water, oral rehydration solution, diluted juice, soup, coconut water. Fever increases fluid loss.</li>
  <li><strong>Dress lightly.</strong> One thin layer. Do not bundle a feverish child in blankets, which traps heat.</li>
  <li><strong>Keep the room comfortable</strong> and well ventilated.</li>
  <li><strong>Let them rest and eat what they will.</strong> Reduced appetite for a day or two is normal; fluids matter far more than food.</li>
  <li><strong>Give paracetamol for discomfort, not for the number.</strong> A child who is comfortable at 38.5&deg;C does not need medicine.</li>
  <li><strong>Check on them overnight</strong> if the fever is high or they seem unwell.</li>
</ul>

<h3>Medicines: doses and cautions</h3>
<ul>
  <li><strong>Paracetamol</strong> is the first choice, dosed strictly by the child's <strong>weight</strong>, not age, and not more often than every four to six hours, with a maximum of four doses in twenty-four hours. Ask your doctor or pharmacist to write the exact millilitres for your child's current weight on the bottle.</li>
  <li><strong>Ibuprofen</strong> may be used in some situations on medical advice, but should be avoided if the child is dehydrated, vomiting, has kidney problems, or if dengue is a possibility, because it increases bleeding risk. During monsoon fever season this matters — see <a href="/blog/monsoon-fever-emergency-ambikapur">monsoon fevers and when they need the ER</a>.</li>
  <li><strong>Never give aspirin</strong> to a child with fever.</li>
  <li><strong>Do not alternate paracetamol and ibuprofen</strong> without medical advice; it causes dosing errors.</li>
  <li><strong>Check every syrup for its strength.</strong> Different brands have different concentrations, and using the old dose with a new bottle is a common cause of overdose.</li>
  <li><strong>Use the measuring device supplied</strong>, never a kitchen spoon.</li>
</ul>

<div class="alert alert-danger mt-3 mb-4 shadow-sm border-0" style="background-color: #f8d7da; border-left: 5px solid #dc3545 !important;">
  <strong>Never give antibiotics left over from a previous illness.</strong> Most childhood fevers are viral, where antibiotics do nothing, cause side effects and drive resistance. Antibiotics should be prescribed after a child has been examined, not started at home because the fever has lasted two days.
</div>

<h3>What not to do</h3>
<ul>
  <li><strong>No cold water or ice baths</strong>, and no sponging with cold water or spirit. These cause shivering, which raises core temperature, and can be dangerous.</li>
  <li><strong>Tepid sponging</strong> is no longer routinely recommended; it does not shorten illness and often distresses the child.</li>
  <li><strong>Do not force food.</strong></li>
  <li><strong>Do not overwrap</strong> to "sweat out" a fever.</li>
</ul>

<h2>Warning Signs: When to See a Doctor</h2>

<h3>Go to hospital immediately, at any hour</h3>
<ul>
  <li><strong>Any fever in a baby under three months</strong>, whatever the child looks like</li>
  <li>Difficulty breathing, fast breathing, grunting, or the chest sucking in between the ribs</li>
  <li>A rash that does not fade when pressed with a glass</li>
  <li>Blue, mottled or very pale skin, or cold hands and feet with a hot body</li>
  <li>Drowsiness, difficulty waking, floppiness, or a weak high-pitched cry</li>
  <li>A fit or convulsion</li>
  <li>Neck stiffness, severe headache, or intolerance of light</li>
  <li>A bulging soft spot in a baby</li>
  <li>Persistent vomiting, or inability to keep fluids down</li>
  <li>No urine for eight to twelve hours, no tears when crying, a dry mouth or sunken eyes</li>
  <li>Severe or worsening abdominal pain</li>
  <li>Any bleeding — gums, nose, or blood in vomit or stool</li>
</ul>

<h3>See a doctor the same day or next morning</h3>
<ul>
  <li>Fever in an infant aged three to six months</li>
  <li>Fever lasting more than three days without improvement</li>
  <li>Fever that settles then returns after a few days</li>
  <li>Ear pain, sore throat with difficulty swallowing, burning urination, or a limp</li>
  <li>A child who is much less active than usual even when the fever comes down</li>
  <li>Any child with a chronic condition, on immunosuppressants, or with a weak immune system</li>
</ul>

<div class="alert alert-warning mt-3 mb-4 shadow-sm border-0" style="background-color: #fff3cd; border-left: 5px solid #ffc107 !important;">
  <strong>The most useful assessment is how the child is between fever spikes.</strong> Give paracetamol, wait an hour, and look again. A child who becomes alert, drinks and plays is usually managing well. A child who stays limp and disinterested even as the temperature falls needs to be seen, whatever the reading was.
</div>

<h2>Febrile Seizures: Frightening, Usually Harmless</h2>
<p>Around one in twenty children between six months and five years has a fit during a fever. To watch, it is terrifying. In the great majority of cases it causes no lasting harm and does not mean the child has epilepsy.</p>

<h3>What to do during a seizure</h3>
<ol>
  <li><strong>Stay calm and note the time.</strong></li>
  <li><strong>Lay the child on their side</strong> on a safe, flat surface away from hard or sharp objects.</li>
  <li><strong>Do not put anything in the mouth</strong> — no spoon, no finger, no cloth, no onion, no key. The child cannot swallow their tongue.</li>
  <li><strong>Do not restrain</strong> the movements or try to hold the limbs still.</li>
  <li><strong>Loosen tight clothing</strong> around the neck.</li>
  <li><strong>Call for help immediately if the fit lasts more than five minutes</strong>, if breathing is difficult, if it repeats, or if the child does not recover normally afterwards.</li>
</ol>
<p>Every first febrile seizure should be assessed by a doctor to confirm the diagnosis and exclude meningitis and other causes.</p>

<h2>When Fever Is Not Just a Virus</h2>
<p>In Surguja, particularly after the rains, fever carries a wider differential than a simple viral illness. Dengue, malaria, typhoid and scrub typhus all need testing rather than watchful waiting when a fever crosses three days. Our guide to <a href="/blog/monsoon-fever-emergency-ambikapur">monsoon fevers in Surguja</a> covers those patterns. Fever with fast breathing points towards <a href="/blog/pneumonia-in-children-symptoms">pneumonia in children</a>; fever with loose motions towards <a href="/blog/diarrhoea-in-children-ors-dehydration">diarrhoea and dehydration</a>; fever with burning urination towards a urinary infection, which in a young child always needs proper investigation.</p>

