<h2>बोन मैरो (अस्थि मज्जा) क्या होता है?</h2>
<p>बोन मैरो हमारी <strong>हड्डियों के अंदर पाया जाने वाला नरम, स्पंज जैसा ऊतक (tissue)</strong> है। यह मुख्य रूप से बड़ी हड्डियों — जैसे कूल्हे की हड्डी, रीढ़, पसलियों, छाती की हड्डी और जांघ की हड्डी — के अंदरूनी हिस्से में भरा रहता है। इसे शरीर की "रक्त फैक्ट्री" कहा जाए तो गलत नहीं होगा, क्योंकि हमारे खून की तीनों मुख्य कोशिकाएँ यहीं बनती हैं। एक स्वस्थ वयस्क का बोन मैरो हर दिन <strong>अरबों नई रक्त कोशिकाएँ</strong> बनाता है।</p>

<blockquote>"बोन मैरो शरीर की सबसे व्यस्त फैक्ट्री है — यह चुपचाप हर सेकंड लाखों नई रक्त कोशिकाएँ बनाता रहता है। जब यह फैक्ट्री गड़बड़ाती है, तो पूरा शरीर प्रभावित होता है।"</blockquote>

<h2>बोन मैरो के मुख्य कार्य</h2>
<p>बोन मैरो का सबसे अहम काम है <strong>रक्त कोशिकाओं का निर्माण (hematopoiesis)</strong>। यह तीन प्रकार की ज़रूरी कोशिकाएँ बनाता है:</p>
<ul>
  <li><strong>लाल रक्त कोशिकाएँ (RBC):</strong> ये शरीर के हर हिस्से तक ऑक्सीजन पहुँचाती हैं। इनकी कमी से एनीमिया (खून की कमी), थकान और <a href="/blog/pairon-me-kamzori">कमजोरी</a> होती है।</li>
  <li><strong>श्वेत रक्त कोशिकाएँ (WBC):</strong> ये शरीर की रक्षा प्रणाली (immunity) का हिस्सा हैं और संक्रमण से लड़ती हैं। इनकी कमी से बार-बार इंफेक्शन होता है।</li>
  <li><strong>प्लेटलेट्स (Platelets):</strong> ये खून का थक्का बनाकर रक्तस्राव रोकती हैं। इनकी कमी से आसानी से नील पड़ना और ब्लीडिंग होती है।</li>
</ul>
<p>इसके अलावा बोन मैरो <strong>स्टेम कोशिकाएँ (stem cells)</strong> भी संग्रहित करता है, जिनसे ये सभी रक्त कोशिकाएँ बनती हैं। यही स्टेम कोशिकाएँ बोन मैरो ट्रांसप्लांट में इस्तेमाल होती हैं।</p>

