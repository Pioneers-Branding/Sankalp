<h2>बोन मैरो की जाँच कैसे होती है?</h2>
<p>बोन मैरो की सेहत जानने के लिए डॉक्टर पहले एक साधारण <strong>ब्लड टेस्ट (CBC)</strong> कराते हैं। अगर उसमें कोई गड़बड़ी दिखे, तो <strong>बोन मैरो एस्पिरेशन और बायोप्सी</strong> की जाती है — इसमें आमतौर पर कूल्हे की हड्डी से थोड़ा सा मैरो निकालकर माइक्रोस्कोप में जाँचा जाता है। यह जाँच ल्यूकेमिया, एनीमिया के प्रकार और अन्य रक्त विकारों की सटीक पहचान में मदद करती है।</p>

<h2>बोन मैरो ट्रांसप्लांट क्या है?</h2>
