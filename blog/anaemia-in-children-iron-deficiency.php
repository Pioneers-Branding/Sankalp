<h2>What Causes It</h2>

<h3>Dietary and feeding causes</h3>
<ul>
  <li><strong>Late or inadequate complementary feeding.</strong> Iron stores from birth run out at around six months, and if solids do not start then, deficiency follows. See <a href="/blog/starting-solids-baby-6-months">starting solids at six months</a>.</li>
  <li><strong>Diets built on milk and refined cereals</strong>, which are low in iron.</li>
  <li><strong>Excessive cow's milk</strong>, particularly before one year. Large volumes displace iron-rich food and can cause microscopic gut bleeding.</li>
  <li><strong>Tea with or after meals</strong>, whose tannins block iron absorption substantially. This is a very common and easily fixed cause in Indian households.</li>
  <li><strong>Purely vegetarian diets</strong> without careful iron and vitamin C combining.</li>
</ul>

<h3>Losses and other causes</h3>
<ul>
  <li><strong>Intestinal worms</strong>, especially hookworm, a major cause in this region — see <a href="/blog/deworming-children-worm-infection">worm infection and deworming</a></li>
  <li><strong>Prematurity or low birth weight</strong>, which means smaller iron stores at birth</li>
  <li><strong>Maternal anaemia in pregnancy</strong></li>
  <li><strong>Repeated infections and diarrhoea</strong></li>
  <li><strong>Heavy menstrual bleeding</strong> in adolescent girls</li>
  <li><strong>Coeliac disease and other malabsorption</strong></li>
  <li><strong>Inherited conditions</strong> such as thalassaemia trait and sickle cell disease, which are relevant in parts of Chhattisgarh and are not treated with iron</li>
</ul>

<h2>Diagnosis</h2>
<p>Pallor is a clue, not a diagnosis. A complete blood count showing haemoglobin, red cell size and other indices is the basic test. Serum ferritin measures iron stores and is the most useful single marker of iron deficiency, though it rises with infection so is interpreted alongside the clinical picture. Where the pattern is unusual, where iron treatment does not work, or where there is a family history, further testing for thalassaemia, sickle cell disease or malabsorption is needed. A stool test may be done where worms are suspected.</p>

<div class="alert alert-danger mt-3 mb-4 shadow-sm border-0" style="background-color: #f8d7da; border-left: 5px solid #dc3545 !important;">
  <strong>Never give iron long-term without a diagnosis.</strong> Not all anaemia is iron deficiency. In thalassaemia trait and sickle cell conditions, iron supplements are unnecessary and prolonged unneeded iron can cause harmful overload. A blood test before starting treatment takes a day and prevents this.
</div>

<h2>Treatment</h2>
<h3>Iron supplementation</h3>
<ul>
  <li><strong>Dose is set by weight</strong> and prescribed by your doctor. Do not guess or copy another child's dose.</li>
  <li><strong>Give on an empty stomach or between meals</strong> where tolerated, since food reduces absorption.</li>
  <li><strong>Give with vitamin C</strong> — a little lemon water, orange or guava markedly improves absorption.</li>
  <li><strong>Never with milk or tea</strong>, and separated by at least an hour from calcium supplements.</li>
  <li><strong>Continue for at least two to three months after the haemoglobin normalises.</strong> This is the most important instruction and the most commonly ignored. Stopping when the blood count is corrected leaves the stores empty and the anaemia returns.</li>
  <li><strong>Expect black stools</strong> — this is harmless and expected. Mild nausea or constipation can be managed by adjusting timing and fluids.</li>
  <li><strong>Use a straw or give with a dropper past the teeth</strong> for liquid iron, which can stain temporarily.</li>
</ul>
<p>Haemoglobin usually begins rising within two to four weeks. If there is no response, the diagnosis, the dose, adherence, ongoing blood loss and malabsorption all need reviewing.</p>

<h3>Alongside supplements</h3>
<ul>
  <li><strong>Deworming</strong> as advised for the age group</li>
  <li><strong>Treating the underlying cause</strong>, whether that is diet, worms, blood loss or malabsorption</li>
  <li><strong>Dietary correction</strong>, which is what prevents recurrence once the course ends</li>
</ul>

