<p class="lead">Anaemia is the most common nutritional disorder in Indian children, and it is also the most under-treated — not because treatment is difficult, but because the condition rarely looks like an illness. There is no fever, no pain, no obvious day when it started. A child who is a little pale, a little tired, a little slower to learn is simply described as quiet or a poor eater. Yet <strong>iron deficiency anaemia in children</strong> has measurable effects on brain development, school performance and infection risk, and correcting it is inexpensive and straightforward.</p>

<h2>Why Iron Matters So Much in Early Childhood</h2>
<p>Iron does two jobs. It carries oxygen in haemoglobin, and it is essential for brain development. The second is why anaemia in the first two years is treated with particular urgency: some of the effects on cognitive development from severe, prolonged iron deficiency in this window may not be fully reversible even after the iron is corrected.</p>
<p>The consequences of untreated anaemia include:</p>
<ul>
  <li>Slowed growth and poor weight gain</li>
  <li>Reduced attention span, slower learning and lower school performance</li>
  <li>More frequent and more severe infections, including <a href="/blog/pneumonia-in-children-symptoms">pneumonia</a> and <a href="/blog/diarrhoea-in-children-ors-dehydration">diarrhoea</a></li>
  <li>Persistent tiredness and irritability</li>
  <li>Reduced physical stamina and appetite, which worsens the deficiency further</li>
</ul>

<blockquote>"Anaemia does not make a child ill. It makes a child slightly less than they would otherwise have been, in every direction at once. That is precisely why it is missed."</blockquote>

