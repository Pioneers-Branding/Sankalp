<h2>Prevention</h2>
<ul>
  <li><strong>Treat maternal anaemia in pregnancy</strong> — see <a href="/blog/first-antenatal-visit-ambikapur">the first antenatal visit</a></li>
  <li><strong>Delayed cord clamping at birth</strong>, which meaningfully increases a newborn's iron stores</li>
  <li><strong>Exclusive breastfeeding to six months</strong>, then iron-rich complementary feeding on time</li>
  <li><strong>Iron and folic acid supplementation</strong> as per the national schedule for infants, children and adolescents</li>
  <li><strong>Regular deworming</strong></li>
  <li><strong>Limit cow's milk</strong> after one year to a reasonable daily amount rather than unlimited</li>
  <li><strong>Screen at-risk children</strong>: preterm and low birth weight babies, those from families with thalassaemia or sickle cell disease, and adolescent girls</li>
  <li><strong>Keep up <a href="/blog/child-vaccination">routine immunisation</a></strong>, since repeated infection worsens anaemia</li>
</ul>

