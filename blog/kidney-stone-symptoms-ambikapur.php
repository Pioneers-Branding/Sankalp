<h3>Risk factors that add up</h3>
<ul>
  <li>Chronically low fluid intake and hot-weather outdoor work</li>
  <li>A high-salt diet, which raises calcium excretion in urine</li>
  <li>High animal protein intake, which raises uric acid and lowers urinary citrate</li>
  <li>Obesity, type 2 diabetes and metabolic syndrome</li>
  <li>Gout, or a family history of stones</li>
  <li>Recurrent urinary tract infections</li>
  <li>Prolonged immobility, and some medicines and supplements including excessive vitamin C</li>
  <li>Bowel disease or previous bowel surgery affecting absorption</li>
</ul>

