  <strong>A common and counterproductive mistake:</strong> cutting out dietary calcium to prevent calcium stones. It usually makes things worse. Calcium eaten with a meal binds oxalate in the gut so it never reaches the urine. Reduce salt and oxalate-heavy foods instead, and keep normal dietary calcium unless your doctor specifically advises otherwise.
</div>

