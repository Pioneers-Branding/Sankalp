<h2>How Stones Are Diagnosed and Treated</h2>
<h3>Diagnosis</h3>
<p>Urine testing for blood, crystals and infection; blood tests for kidney function, calcium and uric acid; an ultrasound of the kidneys, ureters and bladder as the usual first scan; and a low-dose non-contrast CT where the ultrasound is inconclusive, since it identifies size and position most precisely. Any stone that is passed should be sent for analysis, because knowing its composition shapes prevention.</p>

<h3>Treatment, from conservative to surgical</h3>
<ul>
  <li><strong>Watch and wait with medical expulsive therapy.</strong> Stones under about 5 mm often pass spontaneously with high fluid intake, pain relief and medication that relaxes the ureter. Urine is strained to catch the stone.</li>
  <li><strong>Shock wave lithotripsy (ESWL).</strong> Focused shock waves from outside the body break the stone into fragments that pass in the urine. No incision.</li>
  <li><strong>Ureteroscopy with laser.</strong> A fine telescope passes up through the urinary tract and a laser fragments the stone, which is then removed. No external cut. A temporary stent is often placed.</li>
  <li><strong>Percutaneous nephrolithotomy (PCNL).</strong> For large or complex kidney stones, through a small track in the back.</li>
  <li><strong>Emergency drainage.</strong> Where an obstructed kidney is infected, a stent or nephrostomy relieves pressure first and the stone is dealt with afterwards.</li>
</ul>

<h2>Preventing the Next One</h2>
<p>Recurrence is common but far from inevitable, and prevention is mostly about fluid.</p>
<ul>
  <li><strong>Aim for pale straw-coloured urine.</strong> That is the real target, not a fixed number of glasses. In hot months and for outdoor workers, that usually means three litres a day or more.</li>
  <li><strong>Drink through the day, including at night if you wake.</strong> Urine is most concentrated overnight.</li>
  <li><strong>Cut salt sharply.</strong> This is the highest-yield dietary change for calcium stones.</li>
  <li><strong>Add citrus.</strong> Lemon or lime in water raises urinary citrate, which inhibits stone formation.</li>
  <li><strong>Keep normal dietary calcium</strong>, taken with meals.</li>
  <li><strong>Moderate oxalate-heavy foods</strong> — spinach, beetroot, nuts, excessive tea — rather than eliminating them.</li>
  <li><strong>Limit red meat and organ meat</strong> if you form uric acid stones. Our note on <a href="/blog/pair-ke-anguthe-me-dard">gout and uric acid pain</a> is relevant here.</li>
  <li><strong>Get a follow-up scan</strong> after treatment, and a metabolic evaluation if you form stones repeatedly.</li>
</ul>

