<h2>How to Drink Green Tea the Right Way</h2>
<ul>
  <li><strong>Don't use boiling water.</strong> Let it cool to about 80°C. Water that is too hot makes green tea bitter and can irritate the stomach.</li>
  <li><strong>Steep for 2–3 minutes only.</strong> Over-steeping releases more bitter tannins and caffeine.</li>
  <li><strong>Have a light snack first</strong> if you want it in the morning — even a few nuts or a biscuit buffers the acid.</li>
  <li><strong>Keep it to 2–3 cups a day.</strong> More is not better and adds up to a lot of caffeine.</li>
  <li><strong>Skip the sugar.</strong> Added sugar cancels out many of green tea's benefits.</li>
  <li><strong>Don't drink it with iron-rich meals</strong> if you are prone to low iron; leave a gap of an hour or two.</li>
</ul>

