<p>In polycystic ovary syndrome, AMH is characteristically high and should not be read as a sign of superior fertility — it reflects stalled follicles. This is covered in our guide to <a href="/blog/pcos-and-fertility">PCOS and fertility</a>.</p>

<h2>What Lowers AMH</h2>
<ul>
  <li><strong>Age</strong> — the dominant factor by far.</li>
  <li><strong>Genetics and family history.</strong> If your mother had an early menopause, your own timeline may be earlier.</li>
  <li><strong>Ovarian surgery</strong>, particularly removal of endometriomas or ovarian cysts. See <a href="/blog/endometriosis-and-infertility">endometriosis and infertility</a>.</li>
  <li><strong>Chemotherapy and pelvic radiotherapy.</strong> Fertility preservation should be discussed before cancer treatment begins; our <a href="/chemotherapy-hospital-in-ambikapur">oncology department</a> raises this with younger patients.</li>
  <li><strong>Smoking</strong>, which is associated with earlier ovarian ageing.</li>
  <li><strong>Certain autoimmune and genetic conditions</strong>, including fragile X premutation and Turner mosaicism.</li>
  <li><strong>Severe endometriosis</strong> affecting the ovaries.</li>
  <li><strong>Hormonal contraception</strong> can temporarily lower the reading, so mention it when your sample is taken.</li>
  <li><strong>Low vitamin D</strong> has been associated with lower readings in some studies.</li>
</ul>

<h2>Who Should Have the Test</h2>
<ul>
  <li>Women being assessed for infertility, as part of the standard workup</li>
  <li>Before planning IVF, to choose the stimulation protocol and dose</li>
  <li>Women considering egg freezing or delaying pregnancy</li>
  <li>Before cancer treatment, when fertility preservation is being discussed</li>
  <li>Women with a family history of early menopause</li>
  <li>Women who have had ovarian surgery</li>
  <li>Women with irregular cycles, alongside other hormone tests</li>
</ul>
<p>It is less useful as a general screening test for women not currently trying to conceive and not planning treatment, because a result on its own rarely changes what they should do — and frequently causes anxiety out of proportion to its meaning.</p>

<h2>What to Do If Your AMH Is Low</h2>
<p>The instinct is to search for something that will raise the number. Be sceptical of anything promising that. What genuinely helps is a change of strategy, not a supplement.</p>
<ol>
  <li><strong>Do not delay.</strong> This is the single most important response. Low reserve means fewer eggs and, usually, a shorter window. Time is the resource you are short of.</li>
  <li><strong>Complete the rest of the workup.</strong> AMH is one test. Tubal status and semen analysis matter just as much — see <a href="/blog/blocked-fallopian-tubes-hsg-test">the HSG test</a> and <a href="/blog/male-infertility-low-sperm-count">male infertility</a>.</li>
  <li><strong>Stop smoking</strong> entirely, and limit alcohol.</li>
  <li><strong>Correct thyroid function, vitamin D and blood sugar.</strong></li>
  <li><strong>Discuss individualised stimulation.</strong> Low-reserve patients often do better with tailored protocols than with maximum doses.</li>
  <li><strong>Consider embryo or egg banking</strong> across several cycles to accumulate embryos before transfer. See <a href="/blog/frozen-embryo-transfer-explained">embryo freezing and frozen transfer</a>.</li>
  <li><strong>Ask about donor eggs</strong> if your specialist raises it. It is a conversation, not a verdict, and knowing the option exists reduces pressure rather than adding to it.</li>
</ol>

<div class="alert alert-success mt-3 mb-4 shadow-sm border-0" style="background-color: #d4edda; border-left: 5px solid #28a745 !important;">
  <strong>The most encouraging fact about low AMH:</strong> in IVF it predicts how many eggs will be collected, but it is a poor predictor of whether an individual embryo will implant. Women with low reserve who do produce a good embryo have live birth chances driven largely by their age, not by their AMH.
</div>

