<p class="lead">Few numbers cause as much unnecessary distress as a low AMH result. A woman gets a report with a figure on it, searches the internet, reads the phrase "diminished ovarian reserve", and concludes she cannot have children. In most cases that conclusion is simply wrong. The <strong>AMH test</strong> is genuinely useful, but it answers a narrower question than most people think, and understanding exactly what it measures — and what it does not — changes how you should react to your result.</p>

<h2>What AMH Is and What It Measures</h2>
<p>Anti-Müllerian hormone is produced by the small developing follicles in the ovaries. The more of these small follicles a woman has, the higher her AMH. So the test is, in effect, a headcount of the eggs remaining in the reserve pool.</p>
<p>Its practical advantages are real:</p>
<ul>
  <li><strong>It can be taken on any day of the cycle</strong>, unlike day 2&ndash;3 FSH.</li>
  <li><strong>It is relatively stable</strong> from month to month.</li>
  <li><strong>It predicts how the ovary will respond to stimulation drugs</strong> better than any other single test.</li>
</ul>
<p>It is usually interpreted alongside the <strong>antral follicle count</strong>, an ultrasound count of visible small follicles. The two together give a much better picture than either alone.</p>

<blockquote>"AMH counts eggs. It does not grade them. That single distinction explains almost every misunderstanding about this test."</blockquote>

<h2>What AMH Cannot Tell You</h2>
<p>This is the part that gets lost, and it matters more than the number itself.</p>

<div class="table-wrapper"><table class="table">
  <thead>
    <tr><th>AMH does tell you</th><th>AMH does not tell you</th></tr>
  </thead>
  <tbody>
    <tr><td>Roughly how many eggs remain in the pool</td><td>Whether those eggs are chromosomally normal</td></tr>
    <tr><td>How the ovaries are likely to respond to IVF stimulation</td><td>Whether you can conceive naturally this month</td></tr>
    <tr><td>Whether a strong or weak response should be planned for</td><td>Whether your tubes are open or your partner's sperm is normal</td></tr>
    <tr><td>A rough indication of how close menopause may be</td><td>The exact age at which you will reach menopause</td></tr>
  </tbody>
</table></div>

<p>The critical point: <strong>egg quality is determined mainly by age, not by AMH</strong>. A woman of thirty with a low AMH has fewer eggs, but the ones she has are still thirty-year-old eggs, with a thirty-year-old's chance of being chromosomally normal. A woman of forty-two with a reassuringly high AMH has plenty of eggs, but they are forty-two-year-old eggs. That is why age remains the strongest predictor of outcome, as explained in <a href="/blog/ivf-success-rate-by-age">IVF success rate by age</a>.</p>

<div class="alert alert-warning mt-3 mb-4 shadow-sm border-0" style="background-color: #fff3cd; border-left: 5px solid #ffc107 !important;">
  <strong>A low AMH is not a diagnosis of infertility.</strong> Many women with low AMH conceive naturally. What a low result does mean is that the window is likely to be shorter than average, so it is an argument for acting sooner rather than for giving up.
</div>

<h2>How to Read the Result</h2>
<p>Laboratories report AMH in different units, and reference ranges vary between assays, so always interpret your result against the range printed on your own report rather than a figure found online. Broadly, results fall into these bands.</p>

