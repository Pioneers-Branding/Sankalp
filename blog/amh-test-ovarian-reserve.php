    <tr><td><strong>Normal for age</strong></td><td>Reserve appropriate to age</td><td>Standard stimulation protocol expected to work well</td></tr>
    <tr><td><strong>Low for age</strong></td><td>Fewer eggs remaining than typical</td><td>Fewer eggs likely at collection; do not delay treatment</td></tr>
    <tr><td><strong>Very low</strong></td><td>Significantly diminished reserve</td><td>Individualised protocols; realistic counselling; sometimes donor eggs discussed</td></tr>
