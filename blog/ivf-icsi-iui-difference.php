<blockquote>"The question is never 'should we do IVF'. The question is 'which step is failing' — and the answer names the treatment."</blockquote>

<h2>IUI: What It Involves and When It Is Tried First</h2>
<p>Intrauterine insemination is the simplest of the three. Prepared, concentrated sperm is placed directly into the uterus at the time of ovulation, cutting out the journey through the cervix and giving a larger number of good-quality sperm a head start.</p>

<h3>The process</h3>
<ol>
  <li><strong>Cycle monitoring or mild stimulation.</strong> Tablets or low-dose injections encourage one or two follicles to develop, tracked by ultrasound.</li>
  <li><strong>Trigger injection.</strong> Given when a follicle reaches the right size, to time ovulation precisely.</li>
  <li><strong>Semen collection and preparation.</strong> The sample is washed in the laboratory to concentrate the most motile sperm and remove debris and seminal fluid.</li>
  <li><strong>Insemination.</strong> A fine catheter places the prepared sperm into the uterus. It takes a few minutes, needs no anaesthesia, and feels similar to a cervical smear.</li>
  <li><strong>Two-week wait, then a pregnancy test.</strong></li>
</ol>

<h3>When IUI is a sensible first choice</h3>
<ul>
  <li>At least one fallopian tube is confirmed open</li>
  <li>Sperm parameters are mildly reduced, not severely abnormal</li>
  <li>Ovulation problems such as PCOS that respond to tablets</li>
  <li>Cervical factor, or difficulty with intercourse</li>
  <li>Unexplained infertility in a younger woman</li>
</ul>
<p>IUI is inexpensive, quick and low-intervention. Its per-cycle success rate is modest, and most clinics recommend moving on after three to four unsuccessful cycles rather than repeating it indefinitely.</p>

<h2>IVF: The Basic Process, Step by Step</h2>
<p>In-vitro fertilisation moves fertilisation out of the body. Eggs are collected, combined with sperm in the laboratory, and the resulting embryo is placed back into the uterus. It bypasses the fallopian tubes completely, which is why it is the definitive answer to tubal blockage.</p>

