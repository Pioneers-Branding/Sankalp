<h2>Side Effects You Should Expect</h2>
<p>These are common, generally mild, and settle after the cycle.</p>
<ul>
  <li><strong>Bloating and abdominal fullness.</strong> The ovaries genuinely enlarge as multiple follicles grow, so this is expected rather than abnormal.</li>
  <li><strong>Injection site reactions</strong> — redness, bruising, itching or a small lump. Rotating sites and letting the medicine reach room temperature both help.</li>
  <li><strong>Mood swings, irritability and tearfulness</strong> from fluctuating hormone levels, often on top of real anxiety about the outcome.</li>
  <li><strong>Breast tenderness.</strong></li>
  <li><strong>Headaches</strong>, usually mild and helped by hydration and paracetamol.</li>
  <li><strong>Tiredness</strong>, which most women find more pronounced in the second week.</li>
  <li><strong>Mild pelvic discomfort</strong> as the ovaries enlarge.</li>
  <li><strong>Hot flushes</strong>, particularly with agonist protocols.</li>
  <li><strong>Nausea</strong> in some women.</li>
  <li><strong>Constipation or bloating from progesterone</strong> after transfer.</li>
</ul>

<h3>Practical ways to manage them</h3>
<ul>
  <li><strong>Rotate injection sites</strong> and use a fresh spot each time.</li>
  <li><strong>Let refrigerated medicine sit out for a few minutes</strong> before injecting; cold liquid stings more.</li>
  <li><strong>Ice the area briefly before, warm compress after</strong> if bruising is troublesome.</li>
  <li><strong>Drink plenty of fluid</strong> and keep protein intake up during stimulation.</li>
  <li><strong>Wear loose clothing</strong> as bloating develops.</li>
  <li><strong>Keep walking gently</strong>, but stop high-impact exercise and avoid sudden twisting once the ovaries are enlarged, because of the small risk of ovarian torsion.</li>
  <li><strong>Use paracetamol</strong> for headaches rather than NSAIDs, unless your doctor advises otherwise.</li>
  <li><strong>Set alarms</strong> for injection times; consistency matters more than the exact hour.</li>
</ul>

<div class="alert alert-warning mt-3 mb-4 shadow-sm border-0" style="background-color: #fff3cd; border-left: 5px solid #ffc107 !important;">
  <strong>Never miss or delay the trigger injection.</strong> It is timed precisely against the egg collection, usually thirty-four to thirty-six hours ahead. Taking it late, early, or not at all can mean no eggs are retrieved. Confirm the exact time in writing, set two alarms, and call the clinic immediately if anything goes wrong with it.
