<h3>Who is at higher risk</h3>
<ul>
  <li>Women with <a href="/blog/pcos-and-fertility">polycystic ovary syndrome</a> or a high AMH</li>
  <li>Younger women, and those with a low body weight</li>
  <li>A high number of follicles developing, or high oestrogen levels during monitoring</li>
  <li>A previous episode of OHSS</li>
</ul>
<p>Where risk is identified during monitoring, your team can lower the dose, change the trigger drug, or freeze all embryos and transfer in a later cycle — which removes the risk almost entirely. Freezing is explained in <a href="/blog/frozen-embryo-transfer-explained">embryo freezing and frozen embryo transfer</a>.</p>

<h2>Common Worries That Are Not True</h2>
<ul>
  <li><strong>"These injections will bring on early menopause."</strong> They do not. Stimulation rescues follicles that the body was going to discard that month; it does not consume future eggs.</li>
  <li><strong>"IVF drugs cause cancer."</strong> Large long-term studies have not established a causal link with ovarian or breast cancer.</li>
  <li><strong>"More injections mean better results."</strong> Higher doses do not automatically produce more or better eggs, and can increase OHSS risk. The right dose is the one matched to your reserve.</li>
  <li><strong>"The weight gain is permanent."</strong> Most of it is fluid and bloating and resolves within a few weeks of the cycle ending.</li>
  <li><strong>"I must lie down and rest during stimulation."</strong> Normal light activity is fine and better for mood; only high-impact and twisting exercise should stop. See <a href="/blog/how-to-prepare-for-ivf">how to prepare for an IVF cycle</a>.</li>
</ul>

