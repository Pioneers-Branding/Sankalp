<p>Myopia deserves a special mention. It is rising sharply in Indian children, and the two factors most strongly associated with it are prolonged near work and too little time outdoors. Progression matters, because high myopia in adulthood raises the lifetime risk of retinal detachment and glaucoma.</p>

<h2>Warning Signs Parents Should Not Dismiss</h2>
<ul>
  <li>Sitting very close to the television, or holding books unusually near the face</li>
  <li>Squinting, frowning or tilting the head to look at something</li>
  <li>Rubbing the eyes frequently, outside of tiredness</li>
  <li>Frequent headaches, especially in the evening after school</li>
  <li>Complaints that words move, blur or double while reading</li>
  <li>Losing place while reading, or using a finger to track lines beyond the usual age</li>
  <li>Avoiding reading, drawing or other near tasks the child once enjoyed</li>
  <li>A drop in school performance with no other explanation</li>
  <li>One eye that turns in or out, even occasionally or only when tired</li>
  <li>Watering, redness or unusual sensitivity to light</li>
  <li>Clumsiness, poor hand-eye coordination or difficulty with ball games</li>
</ul>

