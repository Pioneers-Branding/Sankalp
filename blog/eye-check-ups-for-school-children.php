<h2>Encouraging Healthy Vision Habits</h2>
<ul>
  <li><strong>Two hours outdoors a day.</strong> Outdoor light is the best-supported protective factor against myopia progression in children.</li>
  <li><strong>The 20-20-20 rule.</strong> Every 20 minutes of near work, look at something about 20 feet away for 20 seconds.</li>
  <li><strong>Screen limits by age</strong>, and no screens in the hour before bed — this protects both eyes and <a href="/blog/neend-na-aana-ke-karan-aur-upay">sleep quality</a>.</li>
  <li><strong>Read in good light</strong>, sitting upright, with the book about a forearm's length away — never lying down or in a moving vehicle.</li>
  <li><strong>Wear the glasses that are prescribed.</strong> Glasses do not weaken eyes; leaving a power uncorrected is what causes strain and, in young children, amblyopia.</li>
  <li><strong>Feed the eyes properly.</strong> Green leafy vegetables, carrots, eggs, milk and seasonal fruit supply the vitamin A that protects the surface of the eye.</li>
  <li><strong>Protective eyewear for sports</strong>, and immediate review after any eye injury at the <a href="/emergency-hospital-in-ambikapur">emergency department</a>.</li>
</ul>

