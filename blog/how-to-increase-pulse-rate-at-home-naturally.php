<h2>Warning Signs You Should Not Ignore</h2>
<p>A slow pulse becomes an emergency when the heart is not pumping enough blood to the brain and body. Seek medical help urgently if a low pulse comes with:</p>
<ul>
  <li>Fainting or near-fainting (blackouts)</li>
  <li>Chest pain or pressure</li>
  <li>Severe shortness of breath</li>
  <li>Confusion or difficulty concentrating</li>
  <li>Extreme weakness or fatigue</li>
  <li>Dizziness that does not settle — especially <a href="/blog/subah-uthte-hi-chakkar-aana-ke-karan">dizziness on getting up</a></li>
</ul>

