<h2>How Doctors Find the Cause</h2>
<p>If your low pulse is causing symptoms, a doctor will usually check your blood pressure, review your medicines, and run an <strong>ECG</strong> to look at the heart's electrical activity. Blood tests (including thyroid and electrolytes) and sometimes a 24-hour Holter monitor or echocardiogram help pinpoint the cause. Most cases are managed simply — by adjusting a medication or treating an underlying issue like an underactive thyroid. In selected cases where the heart's natural pacemaker is failing, a pacemaker may be advised.</p>

<h2>Preventing a Low Pulse</h2>
<p>Keep your heart's rhythm healthy with the same habits that protect the heart overall: stay active, stay hydrated, eat well, sleep enough, manage stress, limit alcohol, and keep conditions like thyroid disease, diabetes and <a href="/blog/bp-high-hone-par-kya-kare">high blood pressure</a> under control. For a complete routine, read our guide to <a href="/blog/heart-health">keeping your heart healthy</a>.</p>

