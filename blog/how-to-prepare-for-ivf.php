<h2>Month Two: Weight, Food, Movement and Sleep</h2>

<h3>Weight</h3>
<p>Both obesity and being significantly underweight reduce IVF success and raise complication rates. If your BMI is high, aim for gradual, sustainable loss of half a kilogram to a kilogram a week. Even a five to ten per cent reduction improves outcomes measurably, particularly in <a href="/blog/pcos-and-fertility">PCOS</a>. Crash dieting during this window is counterproductive.</p>

<h3>Food</h3>
<ul>
  <li><strong>Build meals around protein, vegetables and whole grains.</strong> Dal, eggs, fish, chicken, paneer, curd, nuts and seasonal vegetables.</li>
  <li><strong>Cut refined carbohydrate and sugar</strong> — white rice, maida, bakery items, sweetened tea. This matters most if you have insulin resistance.</li>
  <li><strong>Include healthy fats</strong> from nuts, seeds, and fish.</li>
  <li><strong>Reduce ultra-processed and deep-fried food</strong> rather than obsessing over any single "fertility superfood".</li>
  <li><strong>Limit caffeine</strong> to about one or two cups a day.</li>
  <li><strong>Drink enough water</strong>, particularly through the hot months.</li>
</ul>

<h3>Movement</h3>
<p>Thirty to forty-five minutes of moderate activity most days improves insulin sensitivity, weight and mood. Avoid starting an extreme new training programme; very intense exercise in underweight women can suppress ovulation.</p>

<h3>Sleep</h3>
<p>Seven to eight hours, at consistent times. Poor sleep worsens insulin resistance and raises stress hormones. Our guide to <a href="/blog/neend-na-aana-ke-karan-aur-upay">causes and remedies for poor sleep</a> covers the practical steps.</p>

<h2>What Both Partners Must Stop</h2>
<ul>
  <li><strong>Tobacco, in every form.</strong> Smoking and chewing both reduce success in women and damage sperm DNA in men. This is the single highest-value change either of you can make.</li>
  <li><strong>Alcohol.</strong> Reduce substantially, ideally stop during the preparation period and the cycle itself.</li>
  <li><strong>Anabolic steroids and testosterone supplements</strong> for men — these suppress sperm production, sometimes to zero. See <a href="/blog/male-infertility-low-sperm-count">male infertility and low sperm count</a>.</li>
  <li><strong>Recreational drugs</strong>, including cannabis, which affects sperm parameters.</li>
  <li><strong>Excessive heat for men</strong> — long driving shifts, hot baths, saunas, laptops on the lap.</li>
</ul>

<h2>Month Three: Practical and Emotional Preparation</h2>

<h3>Understand the cycle before it starts</h3>
<p>Ask your team to walk you through the schedule: how many days of injections, how often you will need scans, when egg collection is likely, and what the transfer involves. Our guides to <a href="/blog/ivf-icsi-iui-difference">what IVF, ICSI and IUI involve</a> and <a href="/blog/ivf-injections-side-effects">IVF injections and their side effects</a> cover the details.</p>

<h3>Plan the logistics</h3>
<ul>
  <li><strong>Monitoring visits</strong> come at short notice and cluster over about ten days. Plan work and travel around that window.</li>
  <li><strong>Egg collection</strong> needs sedation, so you will need someone to accompany you and a day off.</li>
  <li><strong>Injections</strong> must be given at consistent times; learn the technique properly and set alarms.</li>
  <li><strong>Storage.</strong> Some medicines need refrigeration.</li>
  <li><strong>Costs.</strong> Get the full estimate in writing, including medication, freezing and any additional procedures. Check our <a href="/empanelments">insurance and scheme empanelments</a>.</li>
</ul>

<h3>Prepare emotionally</h3>
<p>An IVF cycle is demanding in a way that is hard to anticipate — a compressed sequence of hope, waiting and uncertainty. Decide in advance who you will tell and who you will not, agree with your partner how you will handle a negative result, and give yourself permission to step back from social events during the difficult weeks. Our guide to <a href="/blog/stress-management">stress management techniques</a> is worth reading, and our <a href="/psychiatry">mental health service</a> is available if the strain becomes heavy.</p>

<div class="alert alert-success mt-3 mb-4 shadow-sm border-0" style="background-color: #d4edda; border-left: 5px solid #28a745 !important;">
  <strong>A realistic three-month checklist:</strong> correct thyroid, vitamin D, blood sugar and anaemia; treat any uterine or tubal problem; start folic acid; stop tobacco completely; move towards a healthier weight; sleep properly; understand your cycle schedule; and get the costs in writing. Everything on that list is achievable, and together it matters more than any supplement.
</div>

<h2>What Does Not Help</h2>
<ul>
  <li><strong>Complete bed rest</strong> after transfer. Studies show no benefit, and it may be slightly harmful. Normal light activity is advised.</li>
  <li><strong>Extreme diets</strong> or fasting during the preparation window.</li>
  <li><strong>Unproven "immune" treatments</strong> without a clear indication.</li>
  <li><strong>Repeated internet searching for symptoms</strong> during the two-week wait, which reliably increases anxiety and tells you nothing.</li>
  <li><strong>Comparing your protocol with someone else's.</strong> Doses and drugs are tailored to your reserve and response; a different plan is not a worse plan.</li>
</ul>

