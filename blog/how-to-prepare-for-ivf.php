<h3>Supplements with a genuine basis</h3>
<ul>
  <li><strong>Folic acid</strong> for the woman, started now and continued through the first trimester. This is the one non-negotiable.</li>
  <li><strong>Vitamin D</strong>, at a dose based on your measured level rather than guessed.</li>
  <li><strong>A basic preconception multivitamin</strong> covering B12, iodine and iron as needed.</li>
  <li>Your doctor may add others based on your specific situation.</li>
</ul>

<div class="alert alert-warning mt-3 mb-4 shadow-sm border-0" style="background-color: #fff3cd; border-left: 5px solid #ffc107 !important;">
  <strong>Be sceptical of expensive fertility supplement packages.</strong> Evidence for most of the ingredients marketed for "egg quality" is weak, and some have no evidence at all. Spend the money on the medical groundwork above instead, and tell your doctor everything you are taking, since some supplements interact with treatment.
