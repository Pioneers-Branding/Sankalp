<h2>How to Prevent Headaches</h2>
<p>The best way to treat headaches is to stop them happening. Build these habits:</p>
<ul>
<li>Stay consistently hydrated</li>
<li>Keep a regular sleep and meal routine</li>
<li>Take frequent breaks from screens</li>
<li>Manage stress with exercise, breathing, or relaxation</li>
<li>Maintain good posture at your desk and on your phone</li>
<li>Keep a "headache diary" to identify your personal triggers</li>
<li>Exercise regularly and limit alcohol</li>
</ul>

<h2>When to See a Doctor for a Headache</h2>
<p>Most headaches are harmless, but some signal a more serious problem. See a doctor promptly, or seek emergency care, if you have:</p>
<ul>
<li>A sudden, severe headache — the "worst headache of your life"</li>
<li>Headache with fever, stiff neck, confusion, or a rash</li>
<li>Headache after a head injury</li>
<li>Weakness, numbness, difficulty speaking, or vision loss</li>
<li>Headaches that keep getting worse or change in pattern</li>
<li>Headaches with seizures or fainting</li>
<li>Frequent headaches that disrupt daily life or need painkillers often</li>
</ul>

