<h2>What to Feed: Everyday Indian Foods</h2>
<p>There is no need for expensive commercial products. A child grows well on what the household already cooks, adapted for texture and made energy-dense.</p>

<h3>Build every meal from these groups</h3>
<ul>
  <li><strong>Staples for energy:</strong> rice, wheat, ragi, jowar, bajra, suji, poha.</li>
  <li><strong>Protein:</strong> all dals, rajma and chana well cooked and mashed, egg, fish, chicken, paneer, curd.</li>
  <li><strong>Iron-rich foods</strong> at every possible meal: ragi, green leafy vegetables, dals, egg yolk, jaggery, meat and liver where the family eats them. This is the single most important nutritional priority at this age — see <a href="/blog/anaemia-in-children-iron-deficiency">iron deficiency anaemia in children</a>.</li>
  <li><strong>Vitamin C alongside iron</strong> to help absorption: a squeeze of lemon, amla, guava, tomato, orange.</li>
  <li><strong>Added fat for energy density:</strong> half a teaspoon to a teaspoon of ghee or oil in each meal. This is not optional; it is how a small volume carries enough calories.</li>
  <li><strong>Fruit and vegetables:</strong> banana, papaya, mango, chikoo, apple, carrot, pumpkin, sweet potato, spinach.</li>
  <li><strong>Milk products</strong> from six months as part of food — curd, paneer. Cow's milk as a main drink is not recommended before one year.</li>
</ul>

<h3>A practical starting week</h3>
<ol>
  <li><strong>Days 1&ndash;3:</strong> two to three spoons of thick mashed rice or ragi porridge, once a day, with half a teaspoon of ghee.</li>
  <li><strong>Days 4&ndash;7:</strong> add well-mashed dal with rice; increase to two meals.</li>
  <li><strong>Week 2:</strong> add mashed banana or steamed and mashed carrot or pumpkin.</li>
  <li><strong>Week 3:</strong> add curd, mashed potato, khichdi with a little vegetable.</li>
  <li><strong>Week 4:</strong> add mashed egg yolk, then whole egg; add green leafy vegetables finely chopped into khichdi.</li>
</ol>
<p>Introduce one new food at a time and wait two to three days before the next, so any reaction is easy to identify. Expect food to be refused several times before it is accepted; that is normal learning, not dislike.</p>

