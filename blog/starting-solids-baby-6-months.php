<p class="lead">The period between six months and two years is when most childhood undernutrition in India begins, and it is almost never because families lack food. It happens because complementary feeding starts too late, or too early, or because the food given is too watery to carry enough energy. A baby's stomach is small; what goes into it has to be dense. This guide sets out what <strong>starting solids at six months</strong> actually looks like using ordinary household foods, how much to give at each age, and the mistakes that quietly cost a child growth.</p>

<h2>Why Exactly Six Months</h2>
<p>Breast milk alone meets a baby's full nutritional needs for the first six months. From around six months two things change at once: the baby's iron stores, laid down before birth, are running out, and energy needs exceed what milk alone can supply.</p>
<ul>
  <li><strong>Starting too early</strong>, before four months, displaces breast milk, raises the risk of infection and allergy, and the gut and swallowing coordination are not ready.</li>
  <li><strong>Starting too late</strong>, after seven months, risks iron deficiency, poor weight gain, and a child who resists new textures because the window for accepting them has narrowed.</li>
</ul>
<p><strong>Breastfeeding continues alongside</strong>, ideally to two years and beyond. Solids complement milk; they do not replace it.</p>

<blockquote>"Six months is not a suggestion. It is the point at which milk alone stops being enough, and iron is the first thing to run short."</blockquote>

<h2>Signs Your Baby Is Ready</h2>
<ul>
  <li>Can sit with minimal support and hold the head steady</li>
  <li>Shows interest in food, watching and reaching for what others eat</li>
  <li>Opens the mouth when a spoon approaches</li>
  <li>The tongue-thrust reflex, which pushes food out, has faded</li>
  <li>Still seems hungry after full breastfeeds</li>
</ul>

