<h2>Hygiene During Weaning</h2>
<p>Diarrhoeal illness peaks exactly when complementary feeding starts, because food introduces a new route for infection. Wash hands with soap before preparing food and before feeding, wash the child's hands too, use clean utensils, serve food freshly cooked, and avoid storing prepared baby food for long periods in warm weather. Our guides to <a href="/blog/diarrhoea-in-children-ors-dehydration">diarrhoea, ORS and dehydration</a> and <a href="/blog/deworming-children-worm-infection">worm infection and deworming</a> cover this in more detail.</p>

<h2>When to Seek Advice</h2>
<ul>
  <li>The baby is not gaining weight, or is losing weight</li>
  <li>Persistent refusal of all solids beyond seven to eight months</li>
  <li>Choking, gagging or coughing regularly during feeds</li>
  <li>Rash, vomiting, swelling or wheeze after a particular food</li>
  <li>Blood in the stool, or persistent diarrhoea or constipation</li>
  <li>Signs of anaemia — pallor, lethargy, poor appetite</li>
  <li>Any child born preterm or with a medical condition, who needs an individualised plan. See <a href="/blog/level-3-nicu-ambikapur">what a Level-III NICU provides</a> for context on preterm follow-up.</li>
</ul>

