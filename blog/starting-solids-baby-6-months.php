  <strong>Never leave a baby alone with food, and never feed a lying-down or crying child.</strong> Learn what to do if a child chokes before you need it. If a child cannot cough, cry or breathe, this is an emergency &mdash; go to the <a href="/emergency-hospital-in-ambikapur">emergency department</a> immediately while attempting first aid.
