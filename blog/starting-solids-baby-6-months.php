<h2>Responsive Feeding: How, Not Just What</h2>
<ul>
  <li><strong>Feed the child yourself</strong> in the early months, patiently, with eye contact and encouragement.</li>
  <li><strong>Use a separate bowl</strong> so you can see exactly how much the child has eaten.</li>
  <li><strong>Sit the child upright</strong>, ideally with the family at mealtimes.</li>
  <li><strong>No screens, no phone, no distraction feeding.</strong> A distracted child eats without learning hunger and fullness.</li>
  <li><strong>Never force-feed.</strong> It creates food refusal that lasts years.</li>
  <li><strong>Offer a refused food again</strong> on another day. Acceptance often takes eight to ten exposures.</li>
  <li><strong>Let them get messy</strong> with self-feeding from around nine months; it accelerates skill and interest.</li>
  <li><strong>Keep mealtimes to about twenty to thirty minutes</strong>, then stop without pressure.</li>
</ul>

