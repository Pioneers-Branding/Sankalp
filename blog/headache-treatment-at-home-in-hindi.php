<ul>
<li>अचानक बहुत तेज़ सिरदर्द — "ज़िंदगी का सबसे तेज़ दर्द"</li>
<li>बुख़ार, गर्दन में अकड़न, भ्रम या शरीर पर चकत्तों के साथ सिरदर्द</li>
