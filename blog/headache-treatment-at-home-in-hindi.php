<li>कमज़ोरी, सुन्नपन, बोलने में दिक़्क़त या नज़र का धुंधलाना</li>
<li>सिरदर्द जो लगातार बढ़ता जाए या जिसका स्वरूप बदल जाए</li>
<li>दौरे (झटके) या बेहोशी के साथ सिरदर्द</li>
<li>बार-बार होने वाला सिरदर्द जो रोज़मर्रा के काम में बाधा डाले</li>
