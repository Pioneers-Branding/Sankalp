<h2>Which Children Are at Higher Risk</h2>
<ul>
  <li>Babies under one year, particularly under two months</li>
  <li>Children who were preterm or had a low birth weight, including those who spent time in the <a href="/blog/level-3-nicu-ambikapur">neonatal intensive care unit</a></li>
  <li>Malnourished children, and those with <a href="/blog/anaemia-in-children-iron-deficiency">iron deficiency anaemia</a></li>
  <li>Children not exclusively breastfed in the first six months</li>
  <li>Incomplete immunisation, particularly pneumococcal, Hib and measles vaccines</li>
  <li>Exposure to indoor smoke from cooking fires, or to tobacco smoke at home</li>
  <li>Crowded living conditions</li>
  <li>Children with congenital heart disease, chronic lung disease, or a weakened immune system</li>
  <li>Vitamin A and zinc deficiency</li>
</ul>

<h2>Diagnosis and Treatment</h2>
<h3>How it is diagnosed</h3>
<p>Largely clinically — history, breathing rate, chest indrawing and examination with a stethoscope. A pulse oximeter measures oxygen saturation painlessly on a finger or toe. A chest X-ray is used where the diagnosis is unclear or the child is severely unwell, along with blood tests where indicated. Not every child with pneumonia needs an X-ray.</p>

<h3>Treatment</h3>
<ul>
  <li><strong>Mild pneumonia</strong> is usually treated at home with oral antibiotics where a bacterial cause is likely, plus fluids, paracetamol for fever and close observation. Complete the full course even after the child improves.</li>
  <li><strong>Severe pneumonia</strong> needs admission for oxygen, intravenous antibiotics, fluids and monitoring.</li>
  <li><strong>Oxygen is the treatment that saves lives</strong> in severe cases, which is why hospitals with reliable oxygen supply matter so much for childhood pneumonia.</li>
  <li><strong>Cough syrups are not useful</strong> and are not recommended for young children; some contain sedating ingredients that are unsafe.</li>
  <li><strong>Continue feeding and breastfeeding</strong> in small, frequent amounts.</li>
</ul>

<div class="alert alert-warning mt-3 mb-4 shadow-sm border-0" style="background-color: #fff3cd; border-left: 5px solid #ffc107 !important;">
  <strong>Return to the hospital if a child treated at home</strong> develops fast breathing, chest indrawing, cannot drink, becomes drowsy, or is no worse but no better after forty-eight hours of antibiotics. Improvement should be visible by then.
</div>

<h2>Prevention: Where the Real Gains Are</h2>
<ul>
  <li><strong>Complete the immunisation schedule.</strong> Pneumococcal conjugate vaccine, Hib, measles, whooping cough and influenza vaccines together prevent a large share of severe childhood pneumonia. See <a href="/blog/child-vaccination">the childhood vaccination schedule</a>.</li>
  <li><strong>Exclusive breastfeeding for six months</strong>, then continued breastfeeding with appropriate <a href="/blog/starting-solids-baby-6-months">complementary feeding</a>.</li>
  <li><strong>Reduce indoor smoke.</strong> Improved cooking stoves and ventilation make a measurable difference in households using solid fuel.</li>
  <li><strong>No smoking in the house</strong>, ever.</li>
  <li><strong>Handwashing with soap</strong>, and keeping unwell visitors away from small infants.</li>
  <li><strong>Treat malnutrition and anaemia</strong>, which substantially raise both the risk and severity.</li>
  <li><strong>Keep infants warm</strong> in the cold months, particularly newborns — see <a href="/blog/newborn-care-first-40-days">newborn care in the first 40 days</a>.</li>
</ul>

<div class="alert alert-success mt-3 mb-4 shadow-sm border-0" style="background-color: #d4edda; border-left: 5px solid #28a745 !important;">
  <strong>One skill worth having:</strong> if your child has a cough or fever, wait until they are calm, uncover the chest, and count the breaths for a full minute. If the count crosses the threshold for their age, see a doctor today. That single habit catches most pneumonia early.
</div>

