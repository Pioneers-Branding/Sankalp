<p>A child with cough or fever whose breathing rate crosses these thresholds should be seen by a doctor the same day.</p>

<h2>Chest Indrawing and Other Warning Signs</h2>
<p><strong>Chest indrawing</strong> means the lower chest wall moves <em>inwards</em> when the child breathes in, instead of expanding outwards. It happens when the lungs are stiff and the child is working hard to draw air in. It is a sign of severe pneumonia and always means hospital.</p>

<h3>Signs of severe illness</h3>
<ul>
  <li><strong>Chest indrawing</strong>, or the muscles between the ribs pulling in</li>
  <li><strong>Grunting</strong> with each breath</li>
  <li><strong>Head nodding</strong> in time with breathing, in infants</li>
  <li><strong>Nostrils flaring</strong> outwards with each breath</li>
  <li><strong>Blue tinge</strong> around the lips, tongue or fingertips</li>
  <li><strong>Unable to drink or feed</strong>, or vomiting everything</li>
  <li><strong>Drowsiness, difficulty waking, or unusual floppiness</strong></li>
  <li><strong>Convulsions</strong></li>
  <li><strong>Fast breathing that continues even when the fever has come down</strong></li>
</ul>

