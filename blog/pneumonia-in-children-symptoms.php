<p class="lead">Pneumonia remains the largest infectious cause of death in children under five, and the reason is rarely a lack of treatment. It is a delay in recognising it. Families watch a cough and a fever, both of which look like an ordinary cold, and wait. The sign that actually separates pneumonia from a cold is not the cough at all — it is how fast the child is breathing. Learning to count breaths takes sixty seconds and is the most useful skill any parent of a young child can have. This guide explains the <strong>symptoms of pneumonia in children</strong>, how to check for them, and when to go to hospital.</p>

<h2>What Pneumonia Is</h2>
<p>An infection of the lung tissue itself, in which the tiny air sacs fill with fluid and pus. That reduces the surface available for oxygen exchange, so the child compensates by breathing faster and harder. Everything you can observe from outside follows from that single mechanism.</p>
<p>Most cases in young children are caused by viruses. The most serious are bacterial, chiefly pneumococcus and Haemophilus influenzae type b — both of which are covered by routine childhood vaccines.</p>

<blockquote>"Cough tells you the airway is irritated. Fast breathing tells you the lung is struggling. Only the second one is an emergency signal."</blockquote>

<h2>How to Count Breathing Rate</h2>
<p>This is the single most useful check, and it is used by health workers worldwide precisely because it needs no equipment.</p>
<ol>
  <li><strong>Wait until the child is calm</strong> — asleep or resting quietly. A crying or running child breathes fast for obvious reasons.</li>
  <li><strong>Lift or open the clothing</strong> so you can see the chest and abdomen.</li>
  <li><strong>Count each rise of the chest for one full minute</strong>, using a clock or phone timer. Do not count for fifteen seconds and multiply; young children breathe irregularly.</li>
</ol>

