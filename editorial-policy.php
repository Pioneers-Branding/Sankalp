  <h2 id="purpose">1. Purpose of our health content</h2>
  <p>Our Health Blog and information pages are for general health education. They help patients and families understand symptoms, tests and treatment options, and know when to see a doctor. They are not a substitute for a consultation. See our <a href="/medical-disclaimer">Medical Disclaimer</a>.</p>

  <h2 id="ai-use">2. How we use AI</h2>
  <ul>
    <li>Many articles are drafted with the help of AI writing tools and then edited by our team.</li>
    <li>Every blog article shows a red <strong>Medical Disclaimer</strong> notice directly below its title, stating that it is AI-assisted.</li>
    <li>Some images on the website are stock photographs or AI-generated illustrations. They do not show real patients, and they are not presented as photographs of our staff or facilities unless clearly captioned as such.</li>
  </ul>

  <h2 id="review">3. Medical review — what “reviewed” means</h2>
  <p>We describe an article as <strong>“Medically reviewed by [doctor’s name]”</strong> only after that doctor has actually read and approved it. The review date is shown on the article, and we keep a record of the approval. Articles without this statement are credited to the “Sankalp Hospital Editorial Team” and have <strong>not</strong> been individually reviewed by a doctor. We never attribute an article to a doctor who did not write or review it.</p>

  <h2 id="standards">4. Content standards</h2>
  <p>With reference to the Indian Medical Council (Professional Conduct, Etiquette and Ethics) Regulations, 2002, the Drugs and Magic Remedies (Objectionable Advertisements) Act, 1954, the PCPNDT Act, 1994, the ART (Regulation) Act, 2021 and consumer-protection law, our content must <strong>not</strong>:</p>
  <ul>
    <li>promise or guarantee results or cures, or describe procedures as “100% safe”, “painless” or “risk-free”;</li>
    <li>use self-praising comparisons such as “best”, “No. 1” or “only” to describe the hospital or its doctors;</li>
    <li>quote success rates, patient numbers or statistics that we cannot source;</li>
    <li>use invented patient testimonials or stories, or patient photographs without written consent;</li>
    <li>state doctor qualifications or experience that differ from the doctor’s verified profile;</li>
    <li>suggest, directly or indirectly, any facility for foetal sex determination or sex selection;</li>
    <li>offer inducements or discounts in a way that solicits patients.</li>
  </ul>
  <p>Articles should explain when to seek urgent care, give balanced information on benefits and risks, and point to established medical guidance.</p>

  <h2 id="updates">5. Updates and corrections</h2>
